--- Turns a file AST (see tools/dslparser.lua) into a standalone Lua
-- source string that builds the same generator with perchance-lib's
-- native builder API (perchance.Generator / perchance.List). The
-- output needs only `require("perchance")` at run time -- it has no
-- dependency on the DSL parser itself.
local Codegen = {}

--- Produces a Lua string literal. Uses long-bracket form for text
-- containing newlines or quotes (common in Perchance item text) so
-- the generated source stays readable instead of a wall of escapes.
local function luaStringLiteral(s)
  if s:find('[\r\n"]') then
    local level = 0
    while s:find("%]" .. string.rep("=", level) .. "%]") do
      level = level + 1
    end
    local eq = string.rep("=", level)
    return "[" .. eq .. "[" .. s .. "]" .. eq .. "]"
  end
  return string.format("%q", s)
end

local function formatNumber(n)
  if n == math.floor(n) then return tostring(math.floor(n)) end
  return tostring(n)
end

local function emitWeight(weight)
  if weight == nil then return nil end
  if weight.kind == "number" then
    return formatNumber(weight.value)
  elseif weight.kind == "fraction" then
    return formatNumber(weight.num) .. "/" .. formatNumber(weight.den)
  elseif weight.kind == "dynamic" then
    return "perchance.Parser.parse(" .. luaStringLiteral(weight.expr) .. ")"
  end
  error("perchance.codegen: unknown weight kind '" .. tostring(weight.kind) .. "'")
end

local emitItems -- forward declaration (mutually recursive with emitItem)

local function emitItem(item, indent)
  if not item.children and item.weight == nil then
    return luaStringLiteral(item.text)
  end
  local fields = {}
  if item.children then
    fields[#fields + 1] = "value = perchance.List.from("
      .. emitItems(item.children, indent + 1) .. ", " .. luaStringLiteral(item.text) .. ")"
    fields[#fields + 1] = "name = " .. luaStringLiteral(item.text)
  else
    fields[#fields + 1] = "value = " .. luaStringLiteral(item.text)
  end
  local w = emitWeight(item.weight)
  if w then fields[#fields + 1] = "weight = " .. w end
  return "{ " .. table.concat(fields, ", ") .. " }"
end

emitItems = function(items, indent)
  local pad = string.rep("  ", indent)
  local lines = { "{" }
  for _, item in ipairs(items) do
    table.insert(lines, pad .. "  " .. emitItem(item, indent) .. ",")
  end
  table.insert(lines, pad .. "}")
  return table.concat(lines, "\n")
end

--- Generate a standalone Lua script from `fileAST`.
-- `opts.modulePath` overrides the `require(...)` string used to load
-- the runtime (default "perchance"). `opts.sourceName` is used only
-- in the header comment.
function Codegen.generate(fileAST, opts)
  opts = opts or {}
  local modulePath = opts.modulePath or "perchance"
  local out = {}

  local function line(s) table.insert(out, s) end

  line("-- Auto-generated by perchance2lua" .. (opts.sourceName and (" from " .. opts.sourceName) or "") .. ".")
  line("-- Do not hand-edit -- regenerate from the original Perchance generator")
  line("-- source instead. Running this file directly (`lua " .. (opts.outputName or "generated.lua")
    .. "`) prints one generated result; it can also be `require`d as a module")
  line("-- (it still prints once, on first load, and returns the perchance.Generator")
  line("-- object so you can call gen:run() again for more results).")
  line("local perchance = require(" .. luaStringLiteral(modulePath) .. ")")
  line("local gen = perchance.new()")
  line("")

  for _, name in ipairs(fileAST.order) do
    local def = fileAST.defs[name]
    if def.kind == "alias" then
      line("gen:alias(" .. luaStringLiteral(name) .. ", " .. luaStringLiteral(def.text) .. ")")
    else
      line("gen:list(" .. luaStringLiteral(name) .. ", " .. emitItems(def.items, 0) .. ")")
    end
    line("")
  end

  line("gen:setRoot(" .. luaStringLiteral(fileAST.root) .. ")")
  line("")
  line("print(gen:run())")
  line("return gen")

  return table.concat(out, "\n") .. "\n"
end

return Codegen
